const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const {boot} = require('../tests/editor-flows.cjs');
const Safety = require('../js/exam-safety.js');
(async () => {
  const bank = await boot({bank:true});
  bank.run('state.collapsedQuestions={}; renderAll();');
  const duplicate = [...bank.document.querySelectorAll('.qcard button')].find(b=>b.title==='Duplicar questão');
  assert(duplicate && !duplicate.disabled);
  bank.event(duplicate,'click');
  bank.run("state.questions[1].text='SEGUNDA QUESTAO';");
  assert.equal(bank.run('state.questions.length'),2);
  assert.equal(await bank.ctx.EditorTools.saveBank(),true);
  const saved = JSON.parse(bank.requests.filter(r=>r.options.method==='PATCH').at(-1).options.body);
  assert(!JSON.stringify(saved).includes('SEGUNDA QUESTAO'));
  console.log('CONFIRMADO: duplicar no modo banco cria segunda questao; salvar retorna sucesso sem envia-la.');
  const empty = await boot({bank:true});
  empty.run('state.collapsedQuestions={}; renderAll();');
  const remove = [...empty.document.querySelectorAll('.qcard button')].find(b=>b.title==='Remover questão');
  assert(remove && !remove.disabled); empty.event(remove,'click');
  assert.equal(empty.run('state.questions.length'),0);
  await assert.rejects(()=>empty.ctx.EditorTools.saveBank(),/Questão inválida/);
  console.log('CONFIRMADO: salvar banco sem questao rejeita fora do tratamento de erro.');
  const question={type:'caca_palavras',text:'Encontre a palavra',points:'10,0',wordsText:'A'.repeat(30),gridSize:12};
  assert(Safety.inspectExam({school:{totalValue:'10,0'},questions:[question]}).some(i=>i.blocking));
  const exam={id:'e1',review_status:'rascunho',updated_at:'v1',questions:[question],total_value:'10,0'};
  const source=fs.readFileSync('dashboard.html','utf8');
  const context=vm.createContext({exams:[exam],currentProfile:{full_name:'Teste'},hasExamQuestions:()=>true,getExamScoreCheck:()=>({isConsistent:true}),renderExams(){},showToast(){},auth:{getCurrentUser:()=>({email:'fake@example.invalid'}),authenticatedRequest:async (url,opt)=>[{...exam,...JSON.parse(opt.body)}]}});
  vm.runInContext(source.slice(source.indexOf('  async function sendToReview(id)'),source.indexOf('  async function openProfileModal()')),context);
  await vm.runInContext("sendToReview('e1')",context);
  assert.equal(exam.review_status,'enviada');
  console.log('CONFIRMADO: painel envia caca-palavras que a conferencia do editor bloqueia (REST simulado).');
  const print=fs.readFileSync('print.html','utf8');
  const start=print.indexOf('    function printCleanDocument()');
  const body=print.slice(start,print.indexOf('\n    }',start)+6);
  console.log('BOTAO IMPRESSAO:',body);
})().catch(e=>{console.error(e);process.exitCode=1;});
